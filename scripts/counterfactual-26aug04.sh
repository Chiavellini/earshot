#!/usr/bin/env bash
# What WOULD have fired on 2026-08-04, had SPOT and PGR been armed instead of
# recorded.
#
# Both calls were captured to WAV by a record-only path (no detector, no orders
# — docs/history/POSTMORTEM-26AUG04.md). The tape is real, so the detections are
# recoverable after the fact: concatenate the legs in wall-clock order, point a
# single pipe leg at the result, and replay it through the SAME engine and
# keyword set the arm config would have used.
#
# This measures detection only. It cannot recover the race — replay has no book
# and places no orders — but it answers "did the words get said, and when".
set -uo pipefail
cd "$(dirname "$0")/.."

OUT=/tmp/counterfactual-26aug04
mkdir -p "$OUT"

# ── 1. concatenate the keeper legs, chronologically ────────────────────────
# PGR: the 13:51 leg (labelled ...b) came first, then leg01..leg06. Legs 07-23
# are the 12 s "conference has ended" corpses and are excluded.
build_pgr_wav () {
  local list="$OUT/pgr-list.txt"
  : > "$list"
  for f in corpus/bridge-probes/pgr_2026_08_04b.wav \
           corpus/bridge-probes/pgr_2026_08_04_leg0{1,2,3,4,5,6}.wav; do
    [[ -f "$f" ]] && echo "file '$PWD/$f'" >> "$list"
  done
  ffmpeg -nostdin -loglevel error -y -f concat -safe 0 -i "$list" \
         -ac 1 -ar 16000 -c:a pcm_s16le "$OUT/pgr-full.wav"
  echo "  pgr-full.wav: $(python3 -c "
import wave; w=wave.open('$OUT/pgr-full.wav'); print(f'{w.getnframes()/w.getframerate()/60:.1f} min')")"
}

build_spot_wav () {
  cp corpus/bridge-probes/spot_2026_08_04.wav "$OUT/spot-full.wav"
  echo "  spot-full.wav: $(python3 -c "
import wave; w=wave.open('$OUT/spot-full.wav'); print(f'{w.getnframes()/w.getframerate()/60:.1f} min')")"
}

# ── 2. emit a replay config: real keywords, one wav-reading pipe leg ────────
make_replay_cfg () {
  local src_cfg="$1" wav="$2" dest="$3" evid="$4"
  python3 - "$src_cfg" "$wav" "$dest" "$evid" <<'PY'
import re, sys, pathlib
src, wav, dest, evid = sys.argv[1:5]
raw = pathlib.Path(src).read_text(encoding="utf-8")

risk = re.search(r"^\[risk\]", raw, re.M)
kw   = re.search(r"^(# [^\n]*\n)?\[\[keywords\]\]", raw, re.M)
tail = raw[risk.start():kw.start()].rstrip() + "\n\n" + raw[kw.start():].rstrip() + "\n"

series = evid.rsplit("-", 1)[0]
cfg = f'''# COUNTERFACTUAL replay — generated by scripts/counterfactual-26aug04.sh.
# Not an arm config: one pipe leg reads a recorded WAV instead of a live venue.

[event]
id        = "{evid}-REPLAY"
starts_at = "2026-08-04T00:00:00Z"

[pipeline]
chunk_ms       = 80
resample_to_hz = 16000

[detector]
engine = "streaming_ctc"

[detector.streaming_ctc]
model_dir         = "models/sherpa-onnx-streaming-zipformer-ctc-small-2024-03-18"
num_threads       = 1
default_threshold = 0.15
refractory_ms     = 2000

[[sources]]
kind = "pipe"
label = "tape"
sample_rate_hz = 16000
cmd = ["/bin/sh", "-c", "ffmpeg -loglevel error -i {wav} -vn -f s16le -ac 1 -ar 16000 -"]

[kalshi]
series = "{series}"
env = "prod"

'''
pathlib.Path(dest).write_text(cfg + tail, encoding="utf-8")
print(f"  wrote {dest} ({cfg.count('[[keywords]]') + tail.count('[[keywords]]')} keywords)")
PY
}

echo "── building tapes ──"
build_pgr_wav
build_spot_wav

echo "── building replay configs ──"
make_replay_cfg configs/twilio-live-pgr.toml   "$OUT/pgr-full.wav"  "$OUT/pgr-replay.toml"  KXEARNINGSMENTIONPGR-26JUL15
make_replay_cfg configs/spot-26aug04-raw.toml  "$OUT/spot-full.wav" "$OUT/spot-replay.toml" KXEARNINGSMENTIONSPOT-26AUG04

echo "── replaying (speed 0 = as fast as possible) ──"
for name in pgr spot; do
  echo "════ $name ════"
  target/release/earshot replay --config "$OUT/$name-replay.toml" \
      --report "$OUT/$name-report.json" --speed 0 > "$OUT/$name-replay.log" 2>&1
  echo "  exit=$?  log=$OUT/$name-replay.log"
  grep -cE "Confirmed" "$OUT/$name-replay.log" 2>/dev/null | sed 's/^/  Confirmed lines: /'
done
echo "── done; artifacts in $OUT ──"
